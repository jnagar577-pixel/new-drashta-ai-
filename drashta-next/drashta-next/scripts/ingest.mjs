// Ingestion: knowledge/*.md (YAML-style record blocks) -> lib/knowledge-data.js (validated, committed or built before deploy)
import fs from "node:fs"; import path from "node:path"; import { fileURLToPath } from "node:url";
import { parseMarkdownRecords, validateRecord } from "../lib/validate-record.js";
const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(root, "knowledge"), seen = new Set(), records = [], problems = [];
for (const f of fs.readdirSync(dir).filter(f => f.endsWith(".md")).sort())
  for (const r of parseMarkdownRecords(fs.readFileSync(path.join(dir, f), "utf8"))) {
    const e = validateRecord(r); if (seen.has(r.id)) e.push("duplicate id");
    if (e.length) problems.push(`${f} ${r.id}: ${e.join("; ")}`); else { seen.add(r.id); records.push({ ...r, _file: f }); }
  }
if (problems.length) { console.error("INGEST FAILED:\n" + problems.join("\n")); process.exit(1); }
fs.writeFileSync(path.join(root, "lib", "knowledge-data.js"), `// GENERATED by scripts/ingest.mjs - do not edit\nexport const RECORDS = ${JSON.stringify(records, null, 1)};\n`);
console.log(`Ingested ${records.length} records from ${dir}`);
